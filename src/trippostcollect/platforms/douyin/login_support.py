def get_track_simple(distance) -> List[int]:
    # Some detection checks movement speed - constant speed will be detected, so use gradual acceleration
    # distance is the total distance to move
    # Movement track
    track: List[int] = []
    # Current displacement
    current = 0
    # Deceleration threshold
    mid = distance * 4 / 5
    # Time interval
    t = 0.2
    # Initial velocity
    v = 1

    while current < distance:
        if current < mid:
            # Acceleration = 4
            a = 4
        else:
            # Acceleration = -3
            a = -3
        v0 = v
        # Current velocity
        v = v0 + a * t  # type: ignore
        # Movement distance
        move = v0 * t + 1 / 2 * a * t * t
        # Current displacement
        current += move  # type: ignore
        # Add to track
        track.append(round(move))
    return track


